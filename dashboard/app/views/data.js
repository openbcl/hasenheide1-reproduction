// Data and numbers: every number macro of the paper with its source, then citation,
// reproduction, downloads and checksums.
import { h, about, table, fmtBytes, repoLink, viewHeader, segmented, REPO_REF } from "../util.js";
import { PAPER, REF } from "../paper_refs.js";

const CLASSES = {
  data: "recomputed from a committed CSV or table",
  constant: "follows from constants stated in the paper or the README",
  table: "recomputed from a committed table of documented inputs",
  literal: "documented input whose source records are not redistributed (reported, not recomputed)",
};

export async function render(root, { params, meta, load, setParams, views }) {
  const [man, nums] = await Promise.all([load("manifest.json"), load("numbers.json")]);
  const c = meta.citation;
  const doiUrl = c.doi ? `https://doi.org/${c.doi}` : null;

  root.append(
    ...viewHeader(views.find(x => x.id === "data"), REF),
    about("Every number macro of the paper (numbers.tex) with the file it comes from, and how to cite and regenerate " +
      "everything. The table is the package's check of all macros (scripts/check_numbers.py): each value is recomputed " +
      "and compared with numbers.tex, or listed as a documented input."),

    h("h2", {}, "Numbers of the paper"),
    numbersBlock(nums, params, setParams),

    h("h2", {}, "Citing"),
    h("p", {}, "Please cite both the paper and the reproduction package."),
    h("ul", {},
      h("li", {}, "Paper: ", h("i", {}, PAPER.title), `, ${PAPER.authors.replace(/\.$/, "")}. `, PAPER.doi
        ? h("a", { href: `https://doi.org/${PAPER.doi}` }, `doi:${PAPER.doi}`) : "DOI added on publication."),
      h("li", {}, "Reproduction package: ", h("i", {}, c.title), `, version ${c.version} (${c.date_released}). `,
        doiUrl ? h("a", { href: doiUrl, rel: "noopener" }, `doi:${c.doi}`) : null, ". Repository: ",
        h("a", { href: c.repository, rel: "noopener" }, c.repository))),
    h("p", {}, "Licence: ", h("a", { href: "https://creativecommons.org/licenses/by/4.0/", rel: "noopener" }, "CC BY 4.0"),
      ", see ", repoLink(c.repository, "LICENSE"), "."),

    h("h2", {}, "Reproduce"),
    h("p", {}, "Python 3.12 with the pinned requirements; the figures need a LaTeX installation (see README)."),
    h("pre", {}, h("code", {}, [
      "pip install -r requirements.txt",
      "python run_all.py figures --committed   # figures, tables, numbers from the committed data",
      "python scripts/timeseries.py           # time series against their SHA256SUMS",
      "python scripts/build_dashboard_data.py # this dashboard's data (--check: compare only)",
      "cd dashboard && python -m http.server   # view locally at http://localhost:8000",
    ].join("\n"))),

    h("h2", {}, "Test names"),
    h("p", { class: "note" }, "The dashboard names each test after its series, numbered in the order the tests were run. " +
      "The package files keep the ids of the test log, which count the repetitions within an instrument setup " +
      "(S1–S4: where the tripod LEM in F2 and the SICK stood)."),
    table({
      caption: "Tests, package files and instrument setup (results/measurement/timeseries/runs.csv, channels.csv)",
      header: ["Test", "Package file", "Date", "Time zero (local)", "Instrument setup"],
      rows: meta.series.flatMap(s => s.runs).map(id => meta.runs.find(r => r.run === id)).map(r => [r.name,
        h("a", { href: `${c.repository}/blob/${REPO_REF}/results/measurement/timeseries/${r.run}.csv`, rel: "noopener" },
          h("code", {}, `${r.run}.csv`)),
        r.date, r.t0_local.slice(0, 5), r.setup_text]),
    }),

    h("h2", {}, "Files of this dashboard"),
    h("p", { class: "note" }, "Sizes and checksums of every file below, and of every source file, are listed in ",
      h("a", { href: "data/manifest.json", download: "manifest.json" }, h("code", {}, "data/manifest.json")),
      ". The chart library is copied in rather than generated (",
      h("code", {}, "vendor/"), "; origin in ", repoLink(c.repository, "dashboard/vendor/README.md"), ")."),
    table({
      caption: "Generated by scripts/build_dashboard_data.py (deterministic)",
      header: ["File", "Size", "SHA-256"], numeric: [1],
      rows: man.outputs.map(o => {
        const rel = o.path.replace(/^dashboard\//, "");
        return [h("a", { href: rel, download: rel.split("/").pop() }, h("code", {}, rel)), fmtBytes(o.bytes),
                h("code", { title: o.sha256 }, o.sha256.slice(0, 16) + "…")];
      }),
    }),

    h("h2", {}, "Source files"),
    table({
      caption: "Committed files of the reproduction package read by the builder",
      header: ["File", "Size", "SHA-256"], numeric: [1],
      rows: man.sources.map(s => [repoLink(c.repository, s.path), fmtBytes(s.bytes),
                                  h("code", { title: s.sha256 }, s.sha256.slice(0, 16) + "…")]),
    }),

    h("h2", {}, "Privacy"),
    h("p", { class: "note" }, "This site loads nothing from other servers, sets no cookies and uses no analytics. " +
      "A theme you choose is kept in your browser's local storage and never leaves it. The site is hosted on GitHub Pages; " +
      "as any web host, GitHub processes the IP address of each visitor to deliver the pages (",
      h("a", { href: "https://docs.github.com/en/site-policy/privacy-policies/github-general-privacy-statement", rel: "noopener" },
        "GitHub General Privacy Statement"), ")."),
    h("p", { class: "note" }, "Responsible for this site: Brandschutz Consult Ingenieurgesellschaft mbH Leipzig (BCL), " +
      "Torgauer Platz 3, 04315 Leipzig, Germany. ",
      h("a", { href: "https://www.bcl-leipzig.de/impressum/", rel: "noopener" }, "Legal notice (Impressum)"), " · ",
      h("a", { href: "https://www.bcl-leipzig.de/datenschutz/", rel: "noopener" }, "Privacy policy (Datenschutz)"), "."),
  );
}

// searchable table of all macros (numbers_check.csv)
function numbersBlock(nums, params, setParams) {
  const st = { q: params.q || "", cls: Object.hasOwn(CLASSES, params.cls || "") ? params.cls : "all" };
  const count = cls => nums.rows.filter(r => cls === "all" || r.cls === cls).length;
  const holder = h("div");
  const counter = h("p", { class: "chart-note", "aria-live": "polite" });   // one live region, its text changes
  const input = h("input", { type: "search", value: st.q, placeholder: "Search macro, value or source", "aria-label": "Search the numbers",
                             class: "search", oninput: e => { st.q = e.target.value; draw(); } });
  const seg = segmented("Class", ["all", ...Object.keys(CLASSES)].map(c => ({ value: c, label: `${c} (${count(c)})`,
                         title: CLASSES[c] || "all macros" })), st.cls, v => { st.cls = v; draw(); });
  function draw() {
    setParams({ q: st.q || null, cls: st.cls === "all" ? null : st.cls });
    const q = st.q.trim().toLowerCase();
    const rows = nums.rows.filter(r => (st.cls === "all" || r.cls === st.cls) &&
      (!q || `${r.macro} ${r.value} ${r.source}`.toLowerCase().includes(q)));
    counter.textContent = `${rows.length} of ${nums.rows.length} macros` + (st.cls !== "all" ? ` · ${st.cls}: ${CLASSES[st.cls]}` : "");
    holder.replaceChildren(
      table({ caption: "Macro, value as printed, class, source, check status (results/numbers_check.csv)",
              header: ["Macro", "Value", "Class", "Source", "Status"], numeric: [1],
              rows: rows.map(r => [h("code", {}, "\\" + r.macro), r.value, r.cls, h("span", { class: "wrap" }, r.source), r.status]) }));
  }
  draw();
  return h("div", {}, h("div", { class: "controls" }, h("label", { class: "search-label" }, input), seg), counter, holder);
}
