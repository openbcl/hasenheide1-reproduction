"""Generate the data tables of the paper from the committed reduced data.

  tables/experiments_overview.tex     Table 1   results/measurement/experiments_overview.csv
  tables/ambient.tex                  Table 2   results/measurement/ambient.csv
  tables/rst_apartment_runs.tex       Table S4  results/measurement/rst_apartment_runs.csv
  tables/smoke_alarm.tex              Table S7  results/measurement/smoke_alarm_table.csv
  tables/grid_convergence.tex         Table S12 results/simulation/grid_convergence.csv
  tables/fds_sensitivity_results.tex  Table S13 results/simulation/fds_sensitivity{,_nrmse}.csv

The table notes (\\tnote markers) are set in the Supplementary Material around these
fragments.

    python scripts/gen_data_tables.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths as P  # noqa: E402

TABLES_DIR = P.REPO_ROOT / "tables"
SERIES = ["Hep_160_075", "Hep_160_150", "Hep_220_300"]
SERIES_TEX = {s: s.replace("_", r"\_") for s in SERIES}
# geometric ullage-to-diameter range per series (pan and charge geometry, not measured)
H_OVER_D = {"Hep_160_075": "0.53--0.55", "Hep_160_150": "0.51--0.55",
            "Hep_220_300": "0.37--0.40"}


def _si(s: str) -> str:
    """Unit fragments of the CSV case labels -> siunitx."""
    s = re.sub(r'([\d.]+)~\\upmu\$m', r'{}$\\SI{\1}{\\micro\\metre}', s)
    s = re.sub(r'\$([\d.]+/[\d./]+)\$~mm', r'$\1$~\\si{\\milli\\metre}', s)
    s = re.sub(r'\$([\d.]+)\$~mm', r'\\SI{\1}{\\milli\\metre}', s)
    s = re.sub(r'\$\\geq([\d.]+)\\,\\%\$', r'$\\geq$\\SI{\1}{\\percent}', s)
    return s


def _wrap(body: str, name: str, source: str) -> None:
    (TABLES_DIR / f"{name}.tex").write_text(
        f"% Generated by scripts/gen_data_tables.py from {source}. Do not edit by hand.\n{body}",
        encoding="utf-8", newline="\n")
    print(f"wrote tables/{name}.tex")


def gen_ambient() -> None:
    df = pd.read_csv(P.MEAS_RESULTS / "ambient.csv").set_index("series")
    lines = [r"\begin{tabular}{l c c c c}", r"\toprule",
             r"Experiment ID & Runs & $T_\infty$ [\si{\celsius}] & "
             r"$p_\infty$ [\si{\hecto\pascal}] & RH [\si{\percent}] \\", r"\midrule"]
    for s in SERIES:
        r = df.loc[s]
        lines.append(
            f"{SERIES_TEX[s]} & {int(r['n'])} & "
            f"${r['T_mean']:.1f} \\pm {r['T_sd']:.1f}$ & "
            f"${r['BP_mean']:.1f} \\pm {r['BP_sd']:.1f}$ & "
            f"${r['RH_mean']:.1f} \\pm {r['RH_sd']:.1f}$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    _wrap("\n".join(lines) + "\n", "ambient", "results/measurement/ambient.csv")


def gen_experiments_overview() -> None:
    df = pd.read_csv(P.MEAS_RESULTS / "experiments_overview.csv").set_index("series")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}} l c c c c c c}",
             r"\toprule",
             r"Series & Pan [\si{\milli\metre}] & $h/D$ & Mass [\si{\gram}] & Runs & "
             r"$t_\mathrm{flameout}$ [\si{\second}] & $t_\mathrm{vent}$ [\si{\second}] \\", r"\midrule"]
    for s in SERIES:
        r = df.loc[s]
        lines.append(
            f"{SERIES_TEX[s]} & {int(r['pan_mm'])} & {H_OVER_D[s]} & "
            f"{int(r['mass_g'])} & {int(r['runs'])} & "
            f"${r['flameout_mean']:.0f} \\pm {r['flameout_sd']:.0f}$ & "
            f"{int(r['vent_s'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "experiments_overview",
          "results/measurement/experiments_overview.csv")


def _pm_t(m, s):
    return "--" if pd.isna(m) else f"${m:.0f} \\pm {s:.0f}$"


def _pm_k(m, s):
    return "--" if pd.isna(m) else f"${m:.3f} \\pm {s:.3f}$"


def gen_smoke_alarm() -> None:
    df = pd.read_csv(P.MEAS_RESULTS / "smoke_alarm_table.csv").set_index("series")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}} l c c c c c c}",
             r"\toprule",
             r" & \multicolumn{3}{c}{$t_\mathrm{act}$ [\si{\second}]} & "
             r"\multicolumn{2}{c}{$k$ at activation [\si{\per\metre}]} & \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}",
             r"Series & F2 & FC & F3 & F2 & F3 & $n$ \\", r"\midrule"]
    for s in SERIES:
        r = df.loc[s]
        lines.append(
            f"\\textit{{{SERIES_TEX[s]}}} & {_pm_t(r['tF2_mean'], r['tF2_sd'])} & "
            f"{_pm_t(r['tFC_mean'], r['tFC_sd'])} & {_pm_t(r['tF3_mean'], r['tF3_sd'])} & "
            f"{_pm_k(r['kF2_mean'], r['kF2_sd'])} & {_pm_k(r['kF3_mean'], r['kF3_sd'])} & "
            f"{int(r['n'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "smoke_alarm", "results/measurement/smoke_alarm_table.csv")


def gen_rst_apartment_runs() -> None:
    """The six furniture-calorimeter runs on the apartment fuel batch: Y_s pooled over
    all six, Delta H_ch over the four not marked dhch_excluded (table note b)."""
    d = pd.read_csv(P.MEAS_RESULTS / "rst_apartment_runs.csv")
    d = d.sort_values(["pan_mm", "fuel_g"], kind="stable")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}} c c c c c}",
             r"\toprule",
             r"Pan [\si{\milli\metre}] & $m_\mathrm{fuel}$\tnote{a} [\si{\gram}] & "
             r"$\mathrm{TSP}$ [\si{\square\metre}] & $Y_s$ [\si{\gram\per\gram}] & "
             r"$\Delta H_\mathrm{ch}$ [\si{\mega\joule\per\kilo\gram}] \\", r"\midrule"]
    for _, r in d.iterrows():
        dhc = f"${r['dhch_mj']:.2f}$" + (r"\tnote{b}" if r["dhch_excluded"] else "")
        lines.append(f"{int(r['pan_mm'])} & {int(r['fuel_g'])} & ${r['tsp_m2']:.2f}$ & "
                     f"${r['ys_gpg']:.4f}$ & {dhc} \\\\")
    ys = d["ys_gpg"].to_numpy()
    dhc = d.loc[~d["dhch_excluded"], "dhch_mj"].to_numpy()
    lines += [r"\midrule",
              (r"\multicolumn{3}{l}{\textit{Pooled mean "
               f"($n={ys.size}$; $\\Delta H_\\mathrm{{ch}}$: $n={dhc.size}$, note~b)}}}} & "
               f"${ys.mean():.4f} \\pm {ys.std(ddof=1):.4f}$ & "
               f"${dhc.mean():.3f} \\pm {dhc.std(ddof=1):.2f}$ \\\\"),
              r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "rst_apartment_runs",
          "results/measurement/rst_apartment_runs.csv")


def gen_fds_sensitivity_results() -> None:
    """Peak extinction and upper-layer temperature rise per single-parameter case, with the
    deviation from the baseline and the NRMSE against the measurement."""
    df = pd.read_csv(P.SIM_RESULTS / "fds_sensitivity.csv")
    df = df.merge(pd.read_csv(P.SIM_RESULTS / "fds_sensitivity_nrmse.csv")
                  [["run", "nrmse_k_mean", "nrmse_dT_F1"]], on="run", how="left")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}} l l c c c c c c}",
             r"\toprule",
             r" & & \multicolumn{3}{c}{$k$ (LEM, room mean)} "
             r"& \multicolumn{3}{c}{$\Delta T$ (F1 upper)} \\",
             r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
             r"Axis & Case & $\bar k$ & $\Delta_k$ & NRMSE "
             r"& $\Delta T$ & $\Delta_{\Delta T}$ & NRMSE \\",
             r" & & [\si{\per\metre}] & [\si{\percent}] & [\si{\percent}] "
             r"& [\si{\celsius}] & [\si{\percent}] & [\si{\percent}] \\",
             r"\midrule"]
    prev = None
    for _, r in df.iterrows():
        axis = r["group"] if r["group"] != prev else ""
        if axis and prev is not None:
            lines.append(r"\addlinespace[2pt]")
        prev = r["group"]
        if r["run"] == "ysmatched":
            dk = dt = nk = nt = "--"
        else:
            vk = 0.0 if abs(r["dk_mean_pct"]) < 0.05 else r["dk_mean_pct"]
            vt = 0.0 if abs(r["dTu_pct"]) < 0.05 else r["dTu_pct"]
            dk, dt = f"${vk:+.1f}$", f"${vt:+.1f}$"
            nk = f"{r['nrmse_k_mean']:.1f}" if pd.notna(r["nrmse_k_mean"]) else "--"
            nt = f"{r['nrmse_dT_F1']:.1f}" if pd.notna(r["nrmse_dT_F1"]) else "--"
        lines.append(f"{axis} & {_si(r['case'])} & {r['k_mean']:.3f} & {dk} & {nk} & "
                     f"{r['dTu']:.1f} & {dt} & {nt} \\\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "fds_sensitivity_results",
          "results/simulation/fds_sensitivity{,_nrmse}.csv")


def gen_grid_convergence() -> None:
    """Grid convergence of the peak validation quantities (extinction 3 decimals,
    temperature 1 decimal); the F3 ceiling row is a model-only location (note a)."""
    df = pd.read_csv(P.SIM_RESULTS / "grid_convergence.csv")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}} l c c c c c}",
             r"\toprule",
             r" & \multicolumn{4}{c}{peak value} & \\",
             r"\cmidrule(lr){2-5}",
             r"Quantity & uniform $50$ & $25/50$~\si{\milli\metre} & uniform $25$ "
             r"& $12.5/25$~\si{\milli\metre} & $\Delta_{12.5}$ [\si{\percent}] \\", r"\midrule"]
    headers = {"extinction": r"\textit{Light extinction $k$ [\si{\per\metre}], $z=2.3$~\si{\metre}}",
               "temperature": r"\textit{Gas temperature [\si{\celsius}]}"}
    model_only = {"F3 ceiling": "a"}
    for i, group in enumerate(("extinction", "temperature")):
        if i:
            lines.append(r"\midrule")
        lines.append(rf"\multicolumn{{6}}{{l}}{{{headers[group]}}} \\")
        fmt = "{:.3f}" if group == "extinction" else "{:.1f}"
        for _, r in df[df.group == group].iterrows():
            q = str(r["quantity"])
            cells = [q + (rf"\tnote{{{model_only[q]}}}" if q in model_only else ""),
                     fmt.format(r["uni50"]), fmt.format(r["dx25"]), fmt.format(r["uni25"]),
                     fmt.format(r["dx12"]), f"${r['dx12_dev_pct']:+.1f}$"]
            lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "grid_convergence", "results/simulation/grid_convergence.csv")


def main() -> None:
    gen_experiments_overview()
    gen_ambient()
    gen_rst_apartment_runs()
    gen_smoke_alarm()
    gen_grid_convergence()
    gen_fds_sensitivity_results()


if __name__ == "__main__":
    main()
