"""Supplementary Material tables that describe the FDS model, generated from the
production input decks in fds_decks/ (figures stage, committed):

  tables/instrument_positions.tex  <- DEVC/OBST of hep_160_075 (+ hep_220_300 pan)  (Table S1)
  tables/model_meshes.tex          <- MESH, identical in the three production decks  (Table S8)
  tables/model_surfaces.tex        <- SURF (burner surface excepted)                  (Table S9)
  tables/model_materials.tex       <- MATL (+ specific-heat RAMP)                     (Table S10)

The generator cross-checks the decks as it goes: the meshes, surfaces and
materials must be identical in all three production decks, no two meshes may
overlap, every shared mesh face must join cells differing by at most 2:1, each
thermocouple tree must carry 8 sensors in one column, and there must be 6 LEM and
3 SICK beams. Each file is the bare tabular environment; caption, label and table
notes stay in the paper. Run:
  python scripts/gen_model_tables.py
"""
from __future__ import annotations

import re

import numpy as np

import paths as P

TABLES_DIR = P.REPO_ROOT / "tables"
SERIES = ["Hep_160_075", "Hep_160_150", "Hep_220_300"]


def _wrap(body: str, name: str) -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    (TABLES_DIR / f"{name}.tex").write_text(
        f"% Auto-generated by scripts/gen_model_tables.py from fds_decks/. Do not edit by hand.\n{body}",
        encoding="utf-8", newline="\n")
    print(f"wrote {TABLES_DIR / (name + '.tex')}")


PROD_DECKS = {s: P.FDS_DECK_DIR / f"{s.lower()}_ysmatched.fds" for s in SERIES}
_NL_KEY = re.compile(r"([A-Z_]+(?:\([0-9:, ]+\))?)\s*=")


def _deck_namelists(path, group: str) -> list[dict]:
    """All ``&<group>`` namelists of an FDS input file as {KEY: raw value}. A namelist
    may span lines; it ends at the first '/' outside quotes. Quotes are kept in the
    raw value (use _q to strip them)."""
    text = path.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(rf"^&{group}\b", text, flags=re.M):
        i = j = m.end()
        quote = None
        while j < len(text):
            c = text[j]
            if quote:
                quote = None if c == quote else quote
            elif c in "'\"":
                quote = c
            elif c == "/":
                break
            j += 1
        body = text[i:j]
        keys = list(_NL_KEY.finditer(body))
        d = {}
        for k, nxt in zip(keys, keys[1:] + [None]):
            v = body[k.end(): nxt.start() if nxt else len(body)].strip().rstrip(",").strip()
            d[k.group(1).replace(" ", "")] = v
        out.append(d)
    return out


def _q(v: str) -> str:
    return v.strip().strip("'\"")


def _nums(v: str) -> list[float]:
    return [float(x) for x in v.split(",") if x.strip()]


def _same_in_all_series(group: str, drop=lambda d: False) -> list[dict]:
    """Namelists of `group` from the Hep_160_075 deck, after checking the other
    series carry the identical set (entries matching `drop` excluded)."""
    ref = [d for d in _deck_namelists(PROD_DECKS["Hep_160_075"], group) if not drop(d)]
    for s, f in PROD_DECKS.items():
        other = [d for d in _deck_namelists(f, group) if not drop(d)]
        if other != ref:
            raise SystemExit(f"&{group} differs between Hep_160_075 and {s} ({f.name})")
    return ref


def _c(v: float) -> str:
    """A coordinate exactly as written in the input file (no rounding)."""
    return f"{v:.4f}".rstrip("0").rstrip(".") if v % 1 else f"{v:.1f}"


def _mm(v: float) -> str:
    return f"{v * 1000:.0f}"


def gen_model_meshes() -> None:
    """SM (CFD model inputs): the 24 meshes -- bounds, cells, cell size, MPI rank.
    Checks: identical in all three series, no two meshes overlap, and every shared
    face joins cells differing by at most 2:1."""
    meshes = _same_in_all_series("MESH")
    rows = []
    for m in meshes:
        ijk = [int(x) for x in m["IJK"].split(",")]
        xb = _nums(m["XB"])
        size = [(xb[2 * a + 1] - xb[2 * a]) / ijk[a] for a in range(3)]
        rows.append((_q(m["ID"]), xb, ijk, size, int(m.get("MPI_PROCESS", "0"))))
    tol = 1e-9
    for a, (ida, xa, _, sa, _) in enumerate(rows):
        for idb, xb_, _, sb, _ in rows[a + 1:]:
            ov = [min(xa[2 * k + 1], xb_[2 * k + 1]) - max(xa[2 * k], xb_[2 * k]) for k in range(3)]
            if all(o > tol for o in ov):
                raise SystemExit(f"meshes {ida} and {idb} overlap")
            touching = sum(abs(o) <= tol for o in ov) == 1 and all(o >= -tol for o in ov)
            if touching and max(max(sa) / min(sb), max(sb) / min(sa)) > 2 + 1e-6:
                raise SystemExit(f"meshes {ida}/{idb}: cell ratio above 2:1")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l c c c c c c@{}}", r"\toprule",
             r"Mesh & $x$ [\si{\metre}] & $y$ [\si{\metre}] & $z$ [\si{\metre}] "
             r"& Cells ($I{\times}J{\times}K$) & $\delta x$ [\si{\milli\metre}] & MPI rank \\",
             r"\midrule"]
    for mid, xb, ijk, size, rank in rows:
        dx = sorted({_mm(s) for s in size})
        lines.append(
            f"{mid.replace('_', r'\_')} & "
            f"{xb[0]:.2f}--{xb[1]:.2f} & {xb[2]:.2f}--{xb[3]:.2f} & {xb[4]:.2f}--{xb[5]:.2f} & "
            f"${ijk[0]}{{\\times}}{ijk[1]}{{\\times}}{ijk[2]}$ & {'/'.join(dx)} & {rank} \\\\")
    n_cells = sum(np.prod(r[2]) for r in rows)
    lines += [r"\midrule",
              rf"\multicolumn{{4}}{{@{{}}l}}{{Total ({len(rows)} meshes)}} & \num{{{n_cells}}} & & \\",
              r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "model_meshes")


SURF_USE = {"WALL": "walls (default surface)", "CEILING": "ceilings", "FLOOR": "floors",
            "GLASS": "closed windows", "PAN": "fuel pan", "SCALE": "load-cell platform"}
FYI_SHORT = [  # input-file provenance notes -> short form for the table. The decks cite
    # SFPE Handbook 5th ed. Table A.28; the table cites the identical 6th-ed. Table B.7
    # (2026), where the glass entry is "Glass, window" (the deck note says "plate").
    (r"^Building brick, common, sfpe handbook .*table a\.28$", r"SFPE Handbook, Tab.~B.7 (common brick)"),
    (r"^Glass, plate, sfpe handbook .*table a\.28$", r"SFPE Handbook, Tab.~B.7 (window glass)"),
    (r"^Fir, sfpe handbook .*table a\.28$", r"SFPE Handbook, Tab.~B.7 (fir)"),
    (r"^NBSIR 88-3752.*", r"NBSIR 88-3752"),
    (r"^Drysdale, Intro to Fire Dynamics.*", r"Drysdale, Introduction to Fire Dynamics"),
]


def _fyi(v: str) -> str:
    s = _q(v)
    for pat, rep in FYI_SHORT:
        s = re.sub(pat, rep, s, flags=re.I)
    return s.replace("&", r"\&")


def gen_model_surfaces() -> None:
    """SM (CFD model inputs): surfaces (layers, thicknesses, leakage) and the material
    properties behind them, from the production input file (all series identical,
    the burner surface excepted -- it is described in the text)."""
    surfs = _same_in_all_series("SURF", drop=lambda d: "HRRPUA" in d)
    matls = {_q(m["ID"]): m for m in _same_in_all_series("MATL")}
    ramps = {}
    for r in _deck_namelists(PROD_DECKS["Hep_160_075"], "RAMP"):
        ramps.setdefault(_q(r["ID"]), []).append((float(r["T"]), float(r["F"])))
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l l l c@{}}", r"\toprule",
             r"Surface & Used for & Layers from the exposed side (thickness) & Leakage path \\", r"\midrule"]
    for s in surfs:
        sid = _q(s["ID"])
        th = _nums(next(v for k, v in s.items() if k.startswith("THICKNESS")))
        mats = [_q(v) for k, v in sorted(s.items()) if k.startswith("MATL_ID")]
        layers = ", ".join(f"{m.lower()} (\\SI{{{t * 1000:g}}}{{\\milli\\metre}})"
                           for m, t in zip(mats, th))
        leak = "yes" if "LEAK_PATH" in s else "--"
        lines.append(f"{sid} & {SURF_USE.get(sid, '')} & {layers} & {leak} \\\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "model_surfaces")

    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l c c c c >{\raggedright\arraybackslash}p{3.9cm}@{}}", r"\toprule",
             r"Material & $\rho$ [\si{\kilo\gram\per\cubic\metre}] & $k$ "
             r"[\si{\watt\per\metre\per\kelvin}] & $c_p$ [\si{\kilo\joule\per\kilo\gram\per\kelvin}] "
             r"& $\varepsilon$ & Source \\", r"\midrule"]
    for mid, m in matls.items():
        if "SPECIFIC_HEAT_RAMP" in m:
            pts = sorted(ramps[_q(m["SPECIFIC_HEAT_RAMP"])])
            # temperature range of the ramp goes into table note (b) of the SM wrapper
            cp = f"{pts[0][1]:.2f}--{pts[-1][1]:.2f}" + r"\tnote{b}"
        else:
            cp = f"{float(m['SPECIFIC_HEAT']):.2f}"
        eps = f"{float(m['EMISSIVITY']):.2f}" if "EMISSIVITY" in m else r"0.9\tnote{a}"
        lines.append(f"{mid.capitalize()} & {float(m['DENSITY']):.0f} & "
                     f"{float(m['CONDUCTIVITY']):g} & {cp} & {eps} & {_fyi(m['FYI'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "model_materials")


def gen_instrument_positions() -> None:
    """SM S1: positions of the instruments of the experiments, as represented in the
    production input file (the model frame of Figure 1 of the main article). Only
    instruments that existed are listed; model-only outputs (e.g. the F3 thermocouple
    column, the point extinction devices) are excluded."""
    devc = {_q(d["ID"]): d for d in _deck_namelists(PROD_DECKS["Hep_160_075"], "DEVC")
            if "ID" in d}
    def xyz(i):
        return _nums(devc[i]["XYZ"])
    def beam(i):
        return _nums(devc[i]["XB"])
    rows = []
    for size, series in (("160", "Hep_160_075"), ("220", "Hep_220_300")):
        obst = {_q(o.get("ID", "")): o for o in _deck_namelists(PROD_DECKS[series], "OBST")}
        xb = _nums(obst["Fire_pan_00"]["XB"])           # thin plate: its top face burns
        rim = _nums(obst["Fire_pan_01"]["XB"])[5]       # top of the pan wall
        rows.append((f"Burner ({size}\\,mm pan)", "F1",
                     f"{_c(xb[0])}--{_c(xb[1])}", f"{_c(xb[2])}--{_c(xb[3])}", _c(xb[4]),
                     f"burning surface; pan rim at {_c(rim)}"))
    lc = next(o for o in _deck_namelists(PROD_DECKS["Hep_160_075"], "OBST")
              if _q(o.get("ID", "")) == "Load_cell")
    xb = _nums(lc["XB"])
    rows.append(("Load cell", "F1", f"{_c(xb[0])}--{_c(xb[1])}",
                 f"{_c(xb[2])}--{_c(xb[3])}", f"{_c(xb[4])}--{_c(xb[5])}", "platform under the pan"))
    p = xyz("TC_Ceiling_F1")
    rows.append(("Plume thermocouple", "F1", _c(p[0]), _c(p[1]),
                 _c(p[2]), "ceiling above the fire"))
    for room in ("F1", "F2"):
        ids = sorted((i for i in devc if re.fullmatch(rf"TC_{room}_\d_\d", i)),
                     key=lambda i: xyz(i)[2])
        if len(ids) != 8:
            raise SystemExit(f"expected 8 tree thermocouples in {room}, found {len(ids)}")
        x0, y0 = xyz(ids[0])[:2]
        if any(xyz(i)[:2] != [x0, y0] for i in ids):
            raise SystemExit(f"{room} tree thermocouples not in one column")
        zs = ", ".join(f"{xyz(i)[2]:.1f}" for i in ids)
        rows.append(("Thermocouple tree", room, _c(x0), _c(y0),
                     f"{xyz(ids[0])[2]:.1f}--{xyz(ids[-1])[2]:.1f}", f"8 heights: {zs}"))
    lem = sorted((i for i in devc if i.startswith("LEM_LOS_")), key=lambda i: (i[8:10], beam(i)[4]))
    for i in lem:
        b = beam(i)
        room = i.split("_")[2]
        note = "tripod, relocated between runs" if room == "F2" and b[4] < 2.2 else ""
        rows.append(("LEM beam", room, f"{_c(b[0])}--{_c(b[1])}", _c(b[2]), _c(b[4]), note))
    for i in sorted(i for i in devc if i.startswith("SICK_LOS_")):
        b = beam(i)
        rows.append(("SICK beam", i.split("_")[2], f"{_c(b[0])}--{_c(b[1])}",
                     _c(b[2]), _c(b[4]), "to the reflector"))
    for i in sorted((i for i in devc if re.fullmatch(r"SD_[A-Z0-9]+_Hes", i)), key=lambda i: xyz(i)[1]):
        p = xyz(i)
        rows.append(("Smoke alarm", i.split("_")[1], _c(p[0]), _c(p[1]), _c(p[2]), "ceiling"))
    n_lem, n_sick = sum(r[0] == "LEM beam" for r in rows), sum(r[0].startswith("SICK") for r in rows)
    if (n_lem, n_sick) != (6, 3):
        raise SystemExit(f"expected 6 LEM and 3 SICK beams, found {n_lem}/{n_sick}")
    lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l c c c c >{\raggedright\arraybackslash}p{3.6cm}@{}}", r"\toprule",
             r"Instrument & Room & $x$ [\si{\metre}] & $y$ [\si{\metre}] & $z$ [\si{\metre}] & Note \\",
             r"\midrule"]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _wrap("\n".join(lines) + "\n", "instrument_positions")


def main() -> None:
    gen_instrument_positions()
    gen_model_meshes()
    gen_model_surfaces()


if __name__ == "__main__":
    main()
