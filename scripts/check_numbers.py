def device_validation_numbers() -> dict:
    """LEM/SICK slope, max deviation, reproducibility and transmittance accuracy u_tau
    (max deviation as a rectangular bound, in quadrature with the reproducibility)."""
    tex = (P.REPO_ROOT / "tables" / "device_validation_table.tex").read_text(encoding="utf-8")
    out: dict = {}
    for dev in ("LEM", "SICK"):
        m = re.search(rf"{dev}\s*&\s*\d+\s*&\s*\d+\s*&\s*([\d.]+)\s*&\s*([\d.]+)\s*&\s*([\d.]+)", tex)
        slope, maxd, repro = (float(x) for x in m.groups())
        out[f"val{dev}Slope"] = (slope, ".3f")
        out[f"val{dev}MaxDevPct"] = (maxd, ".2f")
        out[f"val{dev}ReproPct"] = (repro, ".2f")
        out[f"val{dev}UtauPct"] = (math.sqrt((maxd / math.sqrt(3)) ** 2 + repro ** 2), ".2f")
    return out


def extinction_budget_numbers() -> dict:
    """Instrument and geometry terms of the k-uncertainty budget (Table S6): u_tau from
    above, optical path L (LEM 0.81 m, SICK 0.80 m), u_L/L = 1.5 %, quoted for
    k = 1.1 and 0.1 1/m; expanded values with coverage factor 2."""
    dev = device_validation_numbers()
    L = {"LEM": 0.81, "SICK": 0.80}
    U_L_REL = 0.015
    K_HI, K_LO = 1.1, 0.1
    out: dict = {}
    for name in ("LEM", "SICK"):
        u_tau = dev[f"val{name}UtauPct"][0] / 100.0
        ell = L[name]
        rel = []
        for k in (K_HI, K_LO):
            tau = math.exp(-k * ell)
            u_k = math.hypot(u_tau / (ell * tau), k * U_L_REL)
            rel.append(u_k / k * 100.0)
        out[f"val{name}BudgetLoPct"] = (rel[0], ".0f")
        out[f"val{name}BudgetHiPct"] = (rel[1], ".0f")
        out[f"val{name}ExpandedLoPct"] = (2 * rel[0], ".0f")
        out[f"val{name}ExpandedHiPct"] = (2 * rel[1], ".0f")
        out[f"val{name}FloorPerM"] = (2 * u_tau / ell, ".3f")
    return out


