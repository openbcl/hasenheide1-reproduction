def ext_peak_obscuration_numbers() -> dict:
    """Fire-room peak measured extinction over the three fires (0.1-rounded) and the
    obscuration per metre 1 - exp(-k) of the rounded values."""
    peaks = []
    for d in _metrics():
        e = d[~d["Unit"].astype(str).str.contains("°")]
        e = e[e["Sensor"].astype(str).str.contains("F1") & ~e["Sensor"].astype(str).str.contains("SICK")]
        peaks.append(float(e["Peak_exp"].max()))
    lo, hi = round(min(peaks), 1), round(max(peaks), 1)
    obsc = lambda k: 100.0 * (1.0 - np.exp(-k))  # noqa: E731
    return {"valExtPeakLoPerM": (lo, ".1f"), "valExtPeakHiPerM": (hi, ".1f"),
            "valObscPeakLoPct": (obsc(lo), ".0f"), "valObscPeakHiPct": (obsc(hi), ".0f")}


def guide_disclosure_numbers() -> dict:
    """Signal-floor exclusions, the most discrepant pair, and the within/between-series
    decomposition (ICC) of the extinction log ratios."""
    d = pd.concat(_metrics(), ignore_index=True)
    is_temp = d["Unit"].astype(str).str.contains("°")
    fin = (np.isfinite(d["Peak_exp"]) & np.isfinite(d["Peak_sim"])
           & (d["Peak_exp"] > 0) & (d["Peak_sim"] > 0))
    temp = d[is_temp & fin]
    ext = d[~is_temp & fin & ~d["Sensor"].astype(str).str.contains("SICK")]
    out = {"valFdsTempExclN": (int((temp["Peak_exp"] < 1.0).sum()), "d"),
           "valFdsExtExclN": (int((ext["Peak_exp"] < 0.02).sum()), "d")}
    ext = ext[ext["Peak_exp"] >= 0.02]
    ln = np.log(ext["Peak_sim"].to_numpy(float) / ext["Peak_exp"].to_numpy(float))
    i = int(np.argmax(np.abs(ln)))
    out["valFdsExtMaxPairRatio"] = (float(np.exp(ln[i])), ".2f")
    out["valFdsDeltaExtExclMax"] = (guide_delta_sigma(np.delete(ln, i), SIGMA_E["Extinction"])["delta"], ".2f")
    per = []
    for e in _metrics():
        e = e[~e["Unit"].astype(str).str.contains("°") & (e["Peak_exp"] >= 0.02)
              & (e["Peak_sim"] > 0) & ~e["Sensor"].astype(str).str.contains("SICK")]
        per.append(np.log(e["Peak_sim"].to_numpy(float) / e["Peak_exp"].to_numpy(float)))
    gm = np.concatenate(per).mean()
    kk = len(per)
    N = sum(len(p) for p in per)
    msb = sum(len(p) * (p.mean() - gm) ** 2 for p in per) / (kk - 1)
    msw = sum(((p - p.mean()) ** 2).sum() for p in per) / (N - kk)
    n0 = (N - sum(len(p) ** 2 for p in per) / N) / (kk - 1)
    var_b = max((msb - msw) / n0, 0.0)
    out["valFdsExtWithinSeriesPct"] = (float(np.sqrt(msw) * 100.0), ".0f")
    out["valFdsExtBetweenIcc"] = (float(var_b / (var_b + msw)) if var_b + msw > 0 else 0.0, ".2f")
    return out


