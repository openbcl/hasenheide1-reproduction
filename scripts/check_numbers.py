"""Recompute the paper's numeric macros (numbers.tex) from the data shipped in this package.

numbers.tex is a static copy of the paper's macros. This script recomputes every macro
it can from the committed reduced data (results/) and the committed table fragments
(tables/), formats it exactly as the paper prints it, and compares the result with
numbers.tex. Each macro ends up in one of four classes:

  data      recomputed from a committed CSV / table fragment
  constant  follows from constants stated in the paper or the README alone (net volume,
            the heat-of-combustion and fire-area scaling factors, the experimental
            uncertainty sigma_E of scripts/guide_stats.py); recomputed and compared
  table     recomputed from a committed table whose entries are themselves documented
            inputs (Table S2: GC composition and SFPE Handbook yields; Table S4: the
            apartment-batch calorimeter runs); four of them also use one of the
            documented literals below as an input (the certified methylcyclohexane share,
            Tewarson's predicted n-heptane yield)
  literal   a documented input whose source records are not redistributed here
            (README, "Provenance of the reported values"); reported, not recomputed

Writes results/numbers_check.csv (macro, value, recomputed, cls, source, status) and
exits non-zero if a recomputed value differs from numbers.tex or a macro is left
unclassified. The table fragments themselves are regenerated by the table targets of
run_all.py; a hand-edited fragment shows up as a difference in `git status`.

    python scripts/check_numbers.py
"""
