def _ext_pairs(e: pd.DataFrame) -> pd.DataFrame:
    """Extinction peak pairs as in the pooled statistic: LEM only, peak >= 0.02 1/m."""
    e = e[~e["Unit"].astype(str).str.contains("°")]
    e = e[~e["Sensor"].astype(str).str.contains("SICK")]
    return e[np.isfinite(e["Peak_exp"]) & np.isfinite(e["Peak_sim"])
             & (e["Peak_exp"] >= 0.02) & (e["Peak_sim"] > 0)]


def fds_height_mechanism_numbers() -> dict:
    """delta_k binned by LEM height: developed layer (z >= 2.2 m) vs interface (z <= 1.6 m)."""
    rows = []
    for e in _metrics():
        for _, r in _ext_pairs(e).iterrows():
            m = re.search(r"([0-9.]+)\s*m", str(r["Sensor"]))
            if m:
                rows.append((float(m.group(1)), np.log(r["Peak_sim"] / r["Peak_exp"])))
    z = np.array([a for a, _ in rows])
    ln = np.array([b for _, b in rows])
    se = SIGMA_E["Extinction"]
    return {"valFdsDeltaExtLowZ": (guide_delta_sigma(ln[z <= 1.6], se)["delta"], ".2f"),
            "valFdsDeltaExtHighZ": (guide_delta_sigma(ln[z >= 2.2], se)["delta"], ".2f")}


def blowerdoor_numbers() -> dict:
    """Air-tightness (SM S2): n50, exponent, effective leakage area, zonal decomposition."""
    d = pd.read_csv(P.MEAS_RESULTS / "blowerdoor_summary.csv")
    q = {(r.test, r.direction): r.q50_m3h for r in d.itertuples()}
    nexp = {(r.test, r.direction): r.n_exp for r in d.itertuples()}
    V_FLUPPE, V_BEMME = 128.0, 130.0            # net volume: FDS (mesh - OBST) / CAD
    V_ROOM = {"F1": 44.4, "F2": 37.4, "F3": 37.9}  # FDS net volume per room
    RHO = 1.194                                  # air density at 22.5 C, 101325 Pa
    a_leak = lambda q50: (q50 / 3600) / (2 * 50 / RHO) ** 0.5  # noqa: E731
    qo, qu = q[("fluppe", "pressurization")], q[("fluppe", "depressurization")]
    Lz = {"F1": q[("F1", "pressurization")],
          "F2": q[("F1F2", "pressurization")] - q[("F1", "pressurization")],
          "F3": q[("F3", "pressurization")]}
    return {
        "valLeakVolume": (V_FLUPPE, ".0f"),
        "valLeakQfiftyOver": (qo, ".0f"),
        "valLeakQfiftyUnder": (qu, ".0f"),
        "valLeakNfiftyOver": (qo / V_FLUPPE, ".1f"),
        "valLeakNfiftyUnder": (qu / V_FLUPPE, ".1f"),
        "valLeakNfiftyMean": ((qo + qu) / 2 / V_FLUPPE, ".1f"),
        "valLeakNExp": (nexp[("fluppe", "pressurization")], ".2f"),
        "valLeakA": (a_leak(qo), ".3f"),
        "valLeakFoneNfifty": (Lz["F1"] / V_ROOM["F1"], ".1f"),
        "valLeakFtwoNfifty": (Lz["F2"] / V_ROOM["F2"], ".1f"),
        "valLeakFthreeNfifty": (Lz["F3"] / V_ROOM["F3"], ".1f"),
        "valLeakChimney": (q[("F3", "pressurization")] - q[("F3_chimney_sealed", "pressurization")], ".0f"),
        "valLeakBemmeNfiftyOver": (q[("bemme", "pressurization")] / V_BEMME, ".1f"),
        "valLeakBemmeNfiftyUnder": (q[("bemme", "depressurization")] / V_BEMME, ".1f"),
    }


